#!/usr/bin/env python3
"""Generate band-limited wavetables for VectorFM.

Six procedural shapes, each rendered additively at 7 mip levels
(128, 64, 32, 16, 8, 4, 2 harmonics max) into 256-sample single cycles
with one guard sample for interpolation. Stored as int16 to fit the
NTS-1 mkII 48KB oscillator budget.

Usage: python3 tools/gen_tables.py > vectorfm/tables.h
"""
import math

TABLE_SIZE = 256
LEVELS = 7
MAX_H = TABLE_SIZE // 2

SHAPES = ["SINE", "TRIANGLE", "SAW", "SQUARE", "FORMANT", "STACK"]


def amps(shape, h):
    """Return (amplitude, phase) of harmonic h for a given shape."""
    if shape == "SINE":
        return (1.0 if h == 1 else 0.0, 0.0)
    if shape == "TRIANGLE":
        if h % 2 == 0:
            return (0.0, 0.0)
        sign = 1.0 if ((h - 1) // 2) % 2 == 0 else -1.0
        return (sign / (h * h), 0.0)
    if shape == "SAW":
        return (1.0 / h, 0.0)
    if shape == "SQUARE":
        return ((1.0 / h) if h % 2 == 1 else 0.0, 0.0)
    if shape == "FORMANT":
        # gentle 1/h body plus a resonant bump around the 6th harmonic
        return (0.35 / h + math.exp(-((h - 6.0) / 1.8) ** 2), 0.0)
    if shape == "STACK":
        # drawbar-style harmonic stack
        stack = {1: 1.0, 2: 0.7, 3: 0.55, 4: 0.45, 6: 0.35, 8: 0.3, 10: 0.2, 12: 0.15, 16: 0.1}
        return (stack.get(h, 0.0), 0.0)
    raise ValueError(shape)


def render(shape, hmax):
    out = []
    for n in range(TABLE_SIZE):
        x = n / TABLE_SIZE
        s = 0.0
        for h in range(1, hmax + 1):
            a, ph = amps(shape, h)
            if a == 0.0:
                continue
            # Lanczos sigma to tame Gibbs ringing
            sigma = 1.0 if h == 1 else math.sin(math.pi * h / (hmax + 1)) / (math.pi * h / (hmax + 1))
            s += a * sigma * math.sin(2.0 * math.pi * h * x + ph)
        out.append(s)
    return out


def main():
    tables = []
    for shape in SHAPES:
        levels = [render(shape, MAX_H >> lvl) for lvl in range(LEVELS)]
        peak = max(max(abs(v) for v in lv) for lv in levels)
        norm = 0.95 / peak
        for lv in levels:
            q = [max(-32767, min(32767, int(round(v * norm * 32767.0)))) for v in lv]
            q.append(q[0])  # guard sample
            tables.append(q)

    print("// Generated by tools/gen_tables.py - do not edit by hand.")
    print("#pragma once")
    print("#include <stdint.h>")
    print()
    print(f"#define VFM_TABLE_SIZE {TABLE_SIZE}")
    print(f"#define VFM_TABLE_BITS {int(math.log2(TABLE_SIZE))}")
    print(f"#define VFM_NUM_SHAPES {len(SHAPES)}")
    print(f"#define VFM_NUM_LEVELS {LEVELS}")
    print("// shapes: " + ", ".join(SHAPES))
    print(f"static const int16_t vfm_tables[VFM_NUM_SHAPES * VFM_NUM_LEVELS][VFM_TABLE_SIZE + 1] = {{")
    for i, t in enumerate(tables):
        shape = SHAPES[i // LEVELS]
        print(f"  // {shape} level {i % LEVELS} ({MAX_H >> (i % LEVELS)} harmonics)")
        print("  {")
        for j in range(0, len(t), 16):
            print("    " + ", ".join(str(v) for v in t[j:j + 16]) + ",")
        print("  },")
    print("};")


if __name__ == "__main__":
    main()
